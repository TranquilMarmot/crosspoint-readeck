import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";

const OUT = "readeck.crosspoint-plugin";
const STATIC = ["device.json", "DETAILS.md"];

// `import html from "./x.html"` gives the file's contents as a string.
// It is emitted as a template literal so the built file shows the HTML as written.
const htmlAsText = {
  name: "html-as-text",

  transform(code, id) {
    if (!id.endsWith(".html")) {
      return null;
    }

    const literal = code
      .replace(/\\/g, "\\\\")
      .replace(/`/g, "\\`")
      .replace(/\$\{/g, "\\${");

    return {
      code: "export default `" + literal + "`;",
      map: null,
    };
  },
};

// `import pkg from "../package.json"` gives only { version }, so the scripts
// and dependencies in package.json stay out of the bundle.
const packageVersion = {
  name: "package-version",

  transform(code, id) {
    if (!id.endsWith("/package.json")) {
      return null;
    }

    const { version } = JSON.parse(code);

    return {
      code: "export default " + JSON.stringify({ version }) + ";",
      map: null,
    };
  },
};

// deletes the plugin folder (`readeck.crosspoint-plugin`) and re-creates it
const pluginFolder = {
  name: "plugin-folder",

  buildStart() {
    rmSync(OUT, { recursive: true, force: true });
    mkdirSync(OUT);

    for (const f of STATIC) {
      copyFileSync("src/" + f, OUT + "/" + f);
      this.addWatchFile("src/" + f);
    }

    // The version comes from package.json, so `npm version` bumps everything.
    const manifest = JSON.parse(readFileSync("src/manifest.json", "utf8"));
    const { version } = JSON.parse(readFileSync("package.json", "utf8"));
    writeFileSync(
      OUT + "/manifest.json",
      JSON.stringify({ ...manifest, version }, null, 2) + "\n",
    );

    this.addWatchFile("src/manifest.json");
    this.addWatchFile("package.json");
  },

  writeBundle() {
    const manifest = JSON.parse(readFileSync(OUT + "/manifest.json", "utf8"));
    const built = readdirSync(OUT).sort();
    const listed = [...manifest.files].sort();

    if (JSON.stringify(built) !== JSON.stringify(listed)) {
      this.error(
        "manifest.json files [" +
          listed.join(", ") +
          "] do not match the built folder [" +
          built.join(", ") +
          "]",
      );
    }
  },
};

export default {
  input: "src/plugin.js",
  plugins: [htmlAsText, packageVersion, pluginFolder],

  onwarn(warning) {
    throw new Error(warning.message);
  },
  output: {
    file: OUT + "/plugin.js",

    // plugin-host.js loads plugin.js as a classic script that must call
    // CrossPoint.registerPlugin while it runs, so the bundle is one IIFE.
    format: "iife",

    banner:
      "// Built from src/ by Rollup (rollup.config.js). Do not edit this file.",
  },
};
